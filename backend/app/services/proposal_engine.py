"""Compatibility helpers for callers of the former slot-matrix engine.

New proposals are generated by proposal_generator_service, which evaluates
real time intervals. These helpers remain available for older integrations but
do not decide or rank proposals.
"""


def required_slots(duration_minutes, slot_minutes=5):
    if duration_minutes <= 0 or slot_minutes <= 0:
        raise ValueError("duration_minutes and slot_minutes must be positive")
    return (duration_minutes + slot_minutes - 1) // slot_minutes


def find_candidates(matrix, min_people, slots_needed):
    candidates = []
    for day, slots in matrix.items():
        times = list(slots.keys())
        for index in range(len(times) - slots_needed + 1):
            window = times[index:index + slots_needed]
            available = [slots[item] for item in window]
            if all(value >= min_people for value in available):
                candidates.append({"day": day, "start": window[0], "score": sum(available)})
    return candidates
